package com.example.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.clickable
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.CheckCircle
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.model.TestQuestion
import com.example.ui.theme.*
import com.example.viewmodel.UniverseUiState

@Composable
fun AiQuizGeneratorScreen(
    uiState: UniverseUiState
) {
    var topic by remember { mutableStateOf("Thermodynamics & Heat Capacity") }
    var subject by remember { mutableStateOf("Physics") }
    var questionCount by remember { mutableStateOf("3") }
    var isGenerated by remember { mutableStateOf(false) }
    var selectedAnswers by remember { mutableStateOf(mapOf<Int, Int>()) }
    var isSubmitted by remember { mutableStateOf(false) }

    val sampleQuestions = remember(topic) {
        listOf(
            TestQuestion(
                id = 1,
                questionText = "For an adiabatic process in an ideal gas, which relationship is strictly conserved?",
                options = listOf("P * V^gamma = constant", "P * V = constant", "T / V = constant", "P / T = constant"),
                correctOptionIndex = 0,
                explanation = "In a reversible adiabatic process, dQ = 0, leading to the relation PV^gamma = constant, where gamma is the adiabatic index."
            ),
            TestQuestion(
                id = 2,
                questionText = "What is the molar heat capacity of an ideal monoatomic gas at constant volume (Cv)?",
                options = listOf("(3/2) R", "(5/2) R", "3 R", "(1/2) R"),
                correctOptionIndex = 0,
                explanation = "A monoatomic gas has 3 translational degrees of freedom, each contributing (1/2) R, so Cv = (3/2) R."
            ),
            TestQuestion(
                id = 3,
                questionText = "In a cyclic thermodynamic process, the net change in internal energy (ΔU) is:",
                options = listOf("Zero", "Equal to heat supplied", "Always positive", "Cannot be determined"),
                correctOptionIndex = 0,
                explanation = "Internal energy U is a state function. Returning to the initial thermodynamic state implies ΔU = 0."
            )
        )
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background)
            .padding(16.dp)
            .verticalScroll(rememberScrollState())
    ) {
        Text(
            text = "🎯 AI Practice Quiz Generator",
            fontSize = 20.sp,
            fontWeight = FontWeight.Bold,
            color = MaterialTheme.colorScheme.onBackground
        )
        Text(
            text = "Generate instant MCQs with explanations tailored to your subject and difficulty level.",
            fontSize = 12.sp,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )

        Spacer(modifier = Modifier.height(16.dp))

        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                OutlinedTextField(
                    value = topic,
                    onValueChange = { topic = it },
                    label = { Text("Topic (e.g. Thermodynamics, Cell Biology)") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth().testTag("ai_quiz_topic_input")
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    OutlinedTextField(
                        value = subject,
                        onValueChange = { subject = it },
                        label = { Text("Subject") },
                        singleLine = true,
                        modifier = Modifier.weight(1f)
                    )
                    OutlinedTextField(
                        value = questionCount,
                        onValueChange = { questionCount = it },
                        label = { Text("Questions") },
                        singleLine = true,
                        modifier = Modifier.weight(1f)
                    )
                }

                Button(
                    onClick = {
                        isGenerated = true
                        selectedAnswers = emptyMap()
                        isSubmitted = false
                    },
                    shape = RoundedCornerShape(12.dp),
                    colors = ButtonDefaults.buttonColors(containerColor = CosmicPurplePrimary),
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(48.dp)
                        .testTag("ai_quiz_generate_btn")
                ) {
                    Text("Generate Quiz Questions", fontWeight = FontWeight.Bold)
                }
            }
        }

        if (isGenerated) {
            Spacer(modifier = Modifier.height(20.dp))

            Text(
                text = "Quiz on: $topic",
                fontSize = 16.sp,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onBackground
            )

            sampleQuestions.forEachIndexed { idx, q ->
                Spacer(modifier = Modifier.height(12.dp))
                Card(
                    shape = RoundedCornerShape(16.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(modifier = Modifier.padding(14.dp)) {
                        Text(
                            text = "Question ${idx + 1}: ${q.questionText}",
                            fontSize = 14.sp,
                            fontWeight = FontWeight.SemiBold,
                            color = MaterialTheme.colorScheme.onSurface
                        )

                        Spacer(modifier = Modifier.height(10.dp))

                        q.options.forEachIndexed { optIdx, optText ->
                            val isChosen = selectedAnswers[q.id] == optIdx
                            Surface(
                                shape = RoundedCornerShape(10.dp),
                                color = if (isChosen) CosmicPurplePrimary.copy(alpha = 0.12f) else MaterialTheme.colorScheme.background,
                                border = androidx.compose.foundation.BorderStroke(
                                    1.dp,
                                    if (isChosen) CosmicPurplePrimary else MaterialTheme.colorScheme.outline.copy(alpha = 0.3f)
                                ),
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(vertical = 4.dp)
                                    .clickable {
                                        if (!isSubmitted) {
                                            selectedAnswers = selectedAnswers + (q.id to optIdx)
                                        }
                                    }
                            ) {
                                Row(
                                    modifier = Modifier.padding(10.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    Text(
                                        text = "${('A' + optIdx)}. ",
                                        fontWeight = FontWeight.Bold,
                                        fontSize = 13.sp,
                                        color = if (isChosen) CosmicPurplePrimary else MaterialTheme.colorScheme.onSurfaceVariant
                                    )
                                    Text(
                                        text = optText,
                                        fontSize = 13.sp,
                                        color = MaterialTheme.colorScheme.onSurface
                                    )
                                }
                            }
                        }

                        if (isSubmitted) {
                            val userPick = selectedAnswers[q.id]
                            val isCorrect = userPick == q.correctOptionIndex
                            Spacer(modifier = Modifier.height(8.dp))
                            Text(
                                text = if (isCorrect) "✅ Correct!" else "❌ Correct: Option ${('A' + q.correctOptionIndex)}",
                                fontSize = 12.sp,
                                fontWeight = FontWeight.Bold,
                                color = if (isCorrect) CosmicSuccess else CosmicError
                            )
                            Text(
                                text = "Explanation: ${q.explanation}",
                                fontSize = 12.sp,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                    }
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            if (!isSubmitted) {
                Button(
                    onClick = { isSubmitted = true },
                    shape = RoundedCornerShape(12.dp),
                    colors = ButtonDefaults.buttonColors(containerColor = CosmicSuccess),
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(48.dp)
                ) {
                    Text("Submit Answers & View Score", fontWeight = FontWeight.Bold)
                }
            } else {
                val correctCount = sampleQuestions.count { selectedAnswers[it.id] == it.correctOptionIndex }
                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = CosmicSuccess.copy(alpha = 0.15f),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Row(
                        modifier = Modifier.padding(16.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.Center
                    ) {
                        Icon(Icons.Default.CheckCircle, contentDescription = null, tint = CosmicSuccess)
                        Spacer(modifier = Modifier.width(8.dp))
                        Text(
                            text = "You scored $correctCount / ${sampleQuestions.size} correct!",
                            fontSize = 15.sp,
                            fontWeight = FontWeight.Bold,
                            color = CosmicSuccess
                        )
                    }
                }
            }
        }
    }
}
